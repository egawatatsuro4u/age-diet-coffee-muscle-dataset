import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy import stats
from sklearn.decomposition import PCA

from common import (COLOURS, GROUPS, LABELS, OUT_DIR, PAIRS, SAMPLES, ensure_out_dir,
                    load, metabolome_wide)

GREY = "#8C8C8C"
SAMPLE_SETS = {"Control": SAMPLES[:3], "AGEs": SAMPLES[3:6], "AGEs+Coffee": SAMPLES[6:]}
PANELS = [("SOL/BW (mg/g)", "soleus_per_bw_mg_g", "Soleus", "Muscle / body weight (mg/g)", 1.0),
          ("GAS/BW (mg/g)", "gastrocnemius_per_bw_mg_g", "Gastrocnemius", "", 1.0),
          ("EDL/BW (mg/g)", "edl_per_bw_mg_g", "EDL", "", 1.0),
          ("Epididymal fat (mg)", "epididymal_fat_mg", "Epididymal fat", "Fat pad (g)", 1e-3)]


def style():
    plt.rcParams.update({"figure.dpi": 120, "savefig.dpi": 600, "font.size": 9,
                         "axes.titlesize": 9, "axes.labelsize": 9, "legend.fontsize": 8,
                         "xtick.labelsize": 8, "ytick.labelsize": 8,
                         "axes.spines.top": False, "axes.spines.right": False,
                         "axes.titlelocation": "left", "axes.titlepad": 6})


def panel_letter(ax, letter):
    ax.text(-0.02, 1.12, letter, transform=ax.transAxes, fontsize=11, fontweight="bold",
            va="top", ha="right")


def figure1(tissue, body_weight, phenotype_stats, out_dir):
    """Phenotype panels with all three pairwise p-values printed per panel."""
    fig = plt.figure(figsize=(11.5, 3.6))
    grid = fig.add_gridspec(1, 5, wspace=0.42)
    ax = fig.add_subplot(grid[0, 0])
    for group in GROUPS:
        series = body_weight[body_weight.group == group].groupby("day").body_weight_g.agg(["mean", "std"])
        ax.errorbar(series.index / 7, series["mean"], yerr=series["std"], color=COLOURS[group],
                    marker="o", ms=2.5, lw=1.3, capsize=1.6, elinewidth=0.8,
                    label=f"{group} ({LABELS[group]})")
    ax.set_xlabel("Week")
    ax.set_ylabel("Body weight (g)")
    ax.set_xticks([0, 2, 4, 6, 8])
    ax.set_title("Body weight")
    ax.margins(0.05)
    # headroom so the legend sits above the curves instead of over them
    ax.set_ylim(top=ax.get_ylim()[1] + 7)
    ax.legend(frameon=False, loc="upper left", handlelength=1.2, borderaxespad=0.1,
              labelspacing=0.25)

    rng = np.random.default_rng(7)
    for position, (metric, column, title, ylabel, scale) in enumerate(PANELS):
        axis = fig.add_subplot(grid[0, position + 1])
        for index, group in enumerate(GROUPS):
            values = tissue.loc[tissue.group == group, column].values * scale
            axis.plot(index + rng.uniform(-0.1, 0.1, len(values)), values, "o",
                      color=COLOURS[group], ms=4.5, alpha=0.9, mew=0)
            axis.plot([index - 0.26, index + 0.26], [values.mean()] * 2,
                      color=COLOURS[group], lw=2.2, solid_capstyle="butt")
        axis.set_xticks(range(3))
        axis.set_xticklabels([LABELS[g] for g in GROUPS])
        axis.set_xlim(-0.55, 2.55)
        axis.set_title(title)
        if ylabel:
            axis.set_ylabel(ylabel)
        lines = []
        for first, second in PAIRS:
            p = phenotype_stats.loc[metric, f"Tukey_p_{first}_vs_{second}"]
            q = phenotype_stats.loc[metric, f"q_BH_{first}_vs_{second}"]
            mark = ("*" if p < 0.05 else "") + ("*" if p < 0.01 else "") + ("\u2020" if q < 0.05 else "")
            lines.append(f"{LABELS[first]} vs {LABELS[second]}  {p:.3f}{mark}")
        low, high = axis.get_ylim()
        axis.set_ylim(low, high + (high - low) * 0.30)
        axis.text(0.5, 0.995, "\n".join(lines), transform=axis.transAxes, ha="center",
                  va="top", fontsize=6.4, color="#3C3C3C", linespacing=1.35)
    for axis, letter in zip(fig.axes, "abcde"):
        panel_letter(axis, letter)
    for suffix in ("png", "pdf"):
        fig.savefig(out_dir / f"Fig1_phenotype.{suffix}", bbox_inches="tight")
    plt.close(fig)


def figure2(long_frame, metabolome_stats, shift_index, out_dir):
    """PCA of the pooled samples and the coffee shift index with its bootstrap CI.

    The index is plotted on a symmetrical-log axis because its bootstrap
    intervals span more than two orders of magnitude; a linear axis would
    require clipping almost every interval.
    """
    wide = metabolome_wide(long_frame)
    matrix = wide.T
    z_scored = (matrix - matrix.mean()) / matrix.std(ddof=1)
    pca = PCA(n_components=2).fit(z_scored.values)
    scores = pca.transform(z_scored.values)
    sample_group = [g for g in GROUPS for _ in range(3)]

    fold_change = np.log2(metabolome_stats["AGEs_mean"] / metabolome_stats["Control_mean"])
    selected = fold_change[np.abs(fold_change) >= np.log2(1.2)].index
    table = shift_index.loc[selected].sort_values("CoffeeShiftIndex")
    spans_zero = (table.boot_CI_lo < 0) & (table.boot_CI_hi > 0)

    fig = plt.figure(figsize=(11.0, 4.6))
    grid = fig.add_gridspec(1, 2, width_ratios=[1, 1.35], wspace=0.10)
    ax = fig.add_subplot(grid[0, 0])
    for group in GROUPS:
        index = [i for i, g in enumerate(sample_group) if g == group]
        ax.plot(scores[index, 0], scores[index, 1], "o", color=COLOURS[group], ms=8, mew=0,
                label=f"{group} ({LABELS[group]})")
    ax.axhline(0, color=GREY, lw=0.7, zorder=0)
    ax.axvline(0, color=GREY, lw=0.7, zorder=0)
    ax.set_xlabel(f"PC1 ({pca.explained_variance_ratio_[0] * 100:.0f}%)")
    ax.set_ylabel(f"PC2 ({pca.explained_variance_ratio_[1] * 100:.0f}%)")
    ax.set_title("Metabolome structure by pooled sample")
    ax.legend(frameon=False, loc="lower right", handlelength=1.0, borderaxespad=0.2)
    ax.margins(0.14)

    axis = fig.add_subplot(grid[0, 1])
    y = np.arange(len(table))
    axis.axvspan(0, 1, color="#DCE6F1", zorder=0)
    for i, (lo, hi, spans) in enumerate(zip(table.boot_CI_lo, table.boot_CI_hi, spans_zero)):
        colour = "#B4B4B4" if spans else "#C44E52"
        axis.hlines(i, lo, hi, color=colour, lw=2.0, zorder=2)
    for spans, colour, label in ((True, "#9A9A9A", "interval includes 0"),
                                 (False, "#C44E52", "interval excludes 0")):
        mask = spans_zero.values == spans
        axis.plot(table.CoffeeShiftIndex.values[mask], y[mask], "o", color=colour, ms=5.5,
                  mew=0, zorder=3, label=f"{label} (n = {int(mask.sum())})")
    axis.axvline(0, color="#3C3C3C", lw=1.0, zorder=1)
    axis.axvline(1, color="#3C3C3C", lw=0.8, ls="--", zorder=1)
    axis.set_xscale("symlog", linthresh=1.0, linscale=1.1)
    axis.set_xlim(-60, 60)
    axis.set_xticks([-10, -1, 0, 1, 10])
    axis.set_xticklabels(["\u221210", "\u22121", "0", "1", "10"])
    axis.set_yticks(y)
    axis.set_yticklabels(table.index, fontsize=7)
    axis.set_ylim(-0.9, len(table) + 0.4)
    axis.set_xlabel("Coffee shift index  (H \u2212 H+C)/(H \u2212 L), symmetrical-log scale")
    axis.set_title(f"{int(spans_zero.sum())} of {len(table)} intervals include zero")
    from matplotlib.patches import Patch
    handles, labels = axis.get_legend_handles_labels()
    handles.append(Patch(facecolor="#DCE6F1", edgecolor="none"))
    labels.append("0 to 1: coffee lies between H and L")
    axis.legend(handles, labels, frameon=False, fontsize=7, handletextpad=0.4, ncol=3,
                loc="upper center", bbox_to_anchor=(0.5, -0.13), columnspacing=1.4)
    axis.yaxis.tick_right()
    for a, letter in zip(fig.axes, "ab"):
        panel_letter(a, letter)
    for suffix in ("png", "pdf"):
        fig.savefig(out_dir / f"Fig2_metabolome_PCA_shift.{suffix}", bbox_inches="tight")
    plt.close(fig)


def figure4(membership, metabolome_stats, out_dir):
    """Pathway means of the member log2 fold changes, for both treatment groups.

    The coffee shift index is deliberately not aggregated to pathway level: its
    denominator is the high-AGE minus low-AGE difference, which is not
    significant for any metabolite, so a pathway-level value would be dominated
    by near-zero denominators.
    """
    members = (membership[membership.in_measured_panel]
               .groupby("pathway").compound.apply(list))
    members = members[members.map(len) >= 3]
    contrasts = {"H vs L": np.log2(metabolome_stats["AGEs_mean"] / metabolome_stats["Control_mean"]),
                 "H+C vs L": np.log2(metabolome_stats["AGEs+Coffee_mean"] / metabolome_stats["Control_mean"])}
    rows = []
    for pathway, compounds in members.items():
        for label, series in contrasts.items():
            values = series.reindex(compounds).dropna().values
            half_width = (stats.sem(values) * stats.t.ppf(0.975, len(values) - 1)
                          if len(values) > 1 else 0.0)
            rows.append({"pathway": pathway, "contrast": label, "n_metabolites": len(values),
                         "mean_log2FC": values.mean(), "ci_lo": values.mean() - half_width,
                         "ci_hi": values.mean() + half_width})
    frame = pd.DataFrame(rows)
    frame["includes_zero"] = (frame.ci_lo < 0) & (frame.ci_hi > 0)
    frame.round(4).to_csv(out_dir / "pathway_group_contrasts.csv", index=False)

    order = frame[frame.contrast == "H vs L"].sort_values("mean_log2FC").pathway.tolist()
    marker = {"H vs L": ("o", COLOURS["AGEs"]), "H+C vs L": ("s", COLOURS["AGEs+Coffee"])}
    fig, ax = plt.subplots(figsize=(7.6, 4.3))
    y = np.arange(len(order))
    for label, offset in (("H vs L", 0.17), ("H+C vs L", -0.17)):
        shape, colour = marker[label]
        series = frame[frame.contrast == label].set_index("pathway").loc[order]
        ax.hlines(y + offset, series.ci_lo, series.ci_hi, color=colour, lw=1.8, alpha=0.85)
        ax.plot(series.mean_log2FC, y + offset, shape, color=colour, ms=5.5, mew=0, label=label)
    ax.axvline(0, color="#3C3C3C", lw=1.0, zorder=0)
    counts = frame[frame.contrast == "H vs L"].set_index("pathway").n_metabolites
    ax.set_yticks(y)
    ax.set_yticklabels([f"{p} (n = {int(counts[p])})" for p in order])
    ax.set_ylim(-0.8, len(order) - 0.2)
    ax.set_xlabel("Mean log\u2082 fold change vs low-AGE control")
    ax.set_title(f"{int(frame.includes_zero.sum())} of {len(frame)} pathway intervals include zero")
    ax.legend(frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.16), ncol=2,
              handletextpad=0.4, columnspacing=2.0)
    ax.margins(x=0.06)
    fig.tight_layout()
    for suffix in ("png", "pdf"):
        fig.savefig(out_dir / f"Fig4_pathway.{suffix}", bbox_inches="tight")
    plt.close(fig)


def figure_s1(run_metadata, long_frame, out_dir):
    """Injection-order diagnostics for the single-batch acquisition."""
    samples = run_metadata[run_metadata.group.isin(GROUPS)].copy()
    is_area = samples.IS_peak_area.astype(float).values
    order = np.arange(1, len(samples) + 1)
    groups = samples.group.tolist()
    wide = metabolome_wide(long_frame)
    correlations = np.array([np.corrcoef(order, wide.iloc[i].values.astype(float))[0, 1]
                             for i in range(len(wide))])
    r_is = np.corrcoef(order, is_area)[0, 1]
    t_is = r_is * np.sqrt(len(order) - 2) / np.sqrt(1 - r_is ** 2)
    p_is = 2 * stats.t.sf(abs(t_is), len(order) - 2)

    fig, axes = plt.subplots(1, 2, figsize=(9.8, 3.8))
    ax = axes[0]
    for group in GROUPS:
        index = [i for i, g in enumerate(groups) if g == group]
        ax.plot(order[index], is_area[index] / 1e6, "o-", color=COLOURS[group], ms=7, lw=1.6,
                label=group)
    ax.axhline(is_area.mean() / 1e6, color=GREY, lw=0.9, ls="--", zorder=0)
    ax.set_xlabel("Injection order (single batch, 3 Feb 2017)")
    ax.set_ylabel("Internal-standard peak area (\u00d710\u2076)")
    ax.set_title(f"No monotonic drift (r = {r_is:.2f}, p = {p_is:.2f})")
    ax.set_xticks(order)
    ax.set_xticklabels(samples["sample"])
    ax.set_xlim(0.4, len(order) + 0.6)
    span = is_area.max() - is_area.min()
    ax.set_ylim((is_area.min() - 0.45 * span) / 1e6, (is_area.max() + 0.12 * span) / 1e6)
    ax.legend(frameon=False, loc="lower center", ncol=3, handletextpad=0.4,
              columnspacing=1.2, borderaxespad=0.2)
    axis = axes[1]
    axis.hist(correlations, bins=np.arange(-1, 1.01, 0.1), color=GREY, edgecolor="white", lw=0.6)
    for value in (-0.7, 0.7):
        axis.axvline(value, color="#C44E52", lw=1.1, ls="--")
    axis.set_xlabel("Correlation with injection order, r")
    axis.set_ylabel(f"Metabolites (of {len(wide)})")
    axis.set_title(f"{int((np.abs(correlations) > 0.7).sum())} of {len(wide)} "
                   f"metabolites exceed |r| = 0.7")
    axis.margins(x=0.02)
    for a, letter in zip(axes, "ab"):
        panel_letter(a, letter)
    fig.subplots_adjust(top=0.84, wspace=0.28)
    for suffix in ("png", "pdf"):
        fig.savefig(out_dir / f"FigS1_injection_order_drift.{suffix}", bbox_inches="tight")
    plt.close(fig)


